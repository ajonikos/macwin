//! Domain messages exchanged between two macwin peers.
//!
//! These are the decoded, validated forms; `macwin-proto` owns the wire
//! encoding. Channel placement:
//! - control stream: session-level traffic (Hello, Heartbeat, Ping/Pong);
//! - input stream: everything that must be totally ordered per direction
//!   (Enter -> ModifierSync -> keys/buttons/wheel -> Leave, TakeControl);
//! - datagrams: latest-wins cursor positions (`MouseAbs`).
//!
//! `Ping`/`Pong` are accepted on every channel and answered on the channel
//! they arrived on.

use crate::types::{
    Hid, ModifierMask, MouseButton, Os, Point, RoleKind, ScreenInfo, Side, WheelUnit,
};

/// The sender can control the receiver (it captures and forwards input).
pub const CAP_INPUT_CAPTURE: &str = "input.capture";
/// The sender can be controlled (it injects input).
pub const CAP_INPUT_INJECT: &str = "input.inject";
/// The sender runs the `spike net` latency tool.
pub const CAP_SPIKE_NET: &str = "spike.net";

/// Messages on the control stream.
#[derive(Debug, Clone, PartialEq)]
pub enum ControlMsg {
    Hello(Hello),
    Heartbeat(Heartbeat),
    Ping(Ping),
    Pong(Pong),
}

/// Messages on the input stream.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum InputMsg {
    Enter(Enter),
    Leave(Leave),
    TakeControl(TakeControl),
    Key(KeyMsg),
    Button(ButtonMsg),
    Wheel(WheelMsg),
    ModifierSync(ModifierMask),
    Ping(Ping),
    Pong(Pong),
}

/// Messages sent as QUIC datagrams.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum DatagramMsg {
    MouseAbs(MouseAbs),
    Ping(Ping),
    Pong(Pong),
}

/// First message on the control stream, sent by both sides.
#[derive(Debug, Clone, PartialEq)]
pub struct Hello {
    /// `major << 16 | minor`.
    pub protocol_version: u32,
    pub capabilities: Vec<String>,
    pub os: Os,
    pub os_version: String,
    pub device_name: String,
    /// The sender's screens in its native coordinates.
    pub screens: Vec<ScreenInfo>,
    /// The sender's configured "peer is to my left/right", if any.
    pub peer_side: Option<Side>,
    pub agent_version: String,
}

impl Hello {
    pub fn has_capability(&self, cap: &str) -> bool {
        self.capabilities.iter().any(|c| c == cap)
    }
}

/// Periodic liveness proof generated by the sender's Engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Heartbeat {
    /// The epoch of the sender's current role (or its highest known epoch
    /// while Idle).
    pub epoch: u64,
    pub role: RoleKind,
}

/// Round-trip probe. `sent_micros` is the sender's own monotonic clock, so no
/// clock synchronisation is needed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Ping {
    pub id: u64,
    pub sent_micros: u64,
}

/// Answer to a [`Ping`], echoing its fields.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pong {
    pub id: u64,
    pub ping_sent_micros: u64,
}

/// The sender starts controlling the receiver.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Enter {
    pub epoch: u64,
    /// Virtual cursor start in the receiver's native coordinates.
    pub at: Point,
}

/// The sender stops controlling the receiver.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Leave {
    pub epoch: u64,
}

/// The sender (currently controlled) saw physical input and takes control
/// back.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TakeControl {
    pub epoch: u64,
}

/// A forwarded key (already remapped by the controller).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct KeyMsg {
    pub hid: Hid,
    pub down: bool,
    pub repeat: bool,
}

/// A forwarded mouse button at the virtual cursor position.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ButtonMsg {
    pub button: MouseButton,
    pub down: bool,
    pub at: Point,
}

/// A forwarded wheel event.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WheelMsg {
    pub dx: i32,
    pub dy: i32,
    pub unit: WheelUnit,
}

/// Latest-wins absolute cursor position in the receiver's native space.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MouseAbs {
    pub epoch: u64,
    pub seq: u64,
    pub at: Point,
}
